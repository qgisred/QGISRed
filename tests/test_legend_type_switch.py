# -*- coding: utf-8 -*-
"""Switching a thematic map between Graduated and Categorized asks to discard only the user's edits.

The legend the other type shows is generated by the switch, so going back and forth without
touching it never asks. Edits the user made are still protected, and coming back to the
legend the layer has leaves nothing pending.
"""
from QGISRed.ui.project.qgisred_legends_dialog import QGISRedLegendsDialog

GRADUATED = "graduatedSymbol"
CATEGORIZED = "categorizedSymbol"


class FakeTypeCombo:
    def __init__(self, value):
        self.value = value
        self.reverted = False

    def currentData(self):
        return self.value


def _dialog(appliedType=GRADUATED, answer=True):
    dialog = QGISRedLegendsDialog.__new__(QGISRedLegendsDialog)
    dialog.currentLayer = object()
    dialog.currentFieldName = "Diameter"
    dialog.currentFieldType = (QGISRedLegendsDialog.FIELD_TYPE_NUMERIC if appliedType == GRADUATED
                               else QGISRedLegendsDialog.FIELD_TYPE_CATEGORICAL)
    dialog.hasUnappliedEdits = False
    dialog.hasUserEdits = False
    dialog.availableUniqueValues = []
    dialog.cbLegendsType = FakeTypeCombo(appliedType)
    dialog.prompts = 0

    def confirm():
        dialog.prompts += 1
        return answer

    dialog.confirmDiscardEdits = confirm
    dialog.revertLegendTypeComboBox = lambda previousType: setattr(dialog.cbLegendsType, "value", previousType)
    dialog.isSingleEditableQueryLayer = lambda: False
    dialog.validateCategorizedConversion = lambda field, currentType: True
    dialog.restoreOriginalCategorizedRenderer = lambda field: appliedType == CATEGORIZED
    dialog.restoreOriginalGraduatedRenderer = lambda field: appliedType == GRADUATED
    dialog.convertToCategorized = lambda field: None
    dialog.convertToGraduated = lambda field: None
    dialog.detectFieldType = lambda layer: (QGISRedLegendsDialog.FIELD_TYPE_NUMERIC, "Diameter")
    for name in ("resetAllModesToManual", "updateUiBasedOnFieldType", "populateLegendTable",
                 "classifyAllUniqueValues", "updateButtonStates", "updateInputLayerRestrictions"):
        setattr(dialog, name, lambda: None)
    dialog.updateFrameLegendLabel = lambda layer: None
    return dialog


def _switch(dialog, newType):
    dialog.cbLegendsType.value = newType
    dialog.onLegendTypeChanged()


class TestSwitchingTheLegendType:
    def test_switching_without_edits_does_not_ask(self):
        dialog = _dialog()
        _switch(dialog, CATEGORIZED)
        assert dialog.prompts == 0 and dialog.currentFieldType == QGISRedLegendsDialog.FIELD_TYPE_CATEGORICAL

    def test_the_switched_legend_is_pending_but_not_an_edit(self):
        dialog = _dialog()
        _switch(dialog, CATEGORIZED)
        assert dialog.hasUnappliedEdits is True and dialog.hasUserEdits is False

    def test_switching_back_and_forth_never_asks(self):
        dialog = _dialog()
        for newType in (CATEGORIZED, GRADUATED, CATEGORIZED, GRADUATED):
            _switch(dialog, newType)
        assert dialog.prompts == 0

    def test_back_on_the_layers_own_legend_nothing_is_pending(self):
        dialog = _dialog()
        _switch(dialog, CATEGORIZED)
        _switch(dialog, GRADUATED)
        assert dialog.hasUnappliedEdits is False

    def test_edits_made_by_the_user_are_protected(self):
        dialog = _dialog(answer=False)
        dialog.markLegendEdited()
        _switch(dialog, CATEGORIZED)
        assert dialog.prompts == 1 and dialog.cbLegendsType.value == GRADUATED
        assert dialog.currentFieldType == QGISRedLegendsDialog.FIELD_TYPE_NUMERIC

    def test_discarding_the_edits_asks_only_once(self):
        dialog = _dialog(answer=True)
        dialog.markLegendEdited()
        _switch(dialog, CATEGORIZED)
        _switch(dialog, GRADUATED)
        _switch(dialog, CATEGORIZED)
        assert dialog.prompts == 1

    def test_applying_clears_the_user_edits(self):
        dialog = _dialog()
        dialog.markLegendEdited()
        dialog.clearLegendEdited()
        assert dialog.hasUserEdits is False and dialog.hasUnappliedEdits is False
